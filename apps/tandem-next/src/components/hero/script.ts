/** Display label for a worker name: "sonnet-14" → "sonnet 5.5". */
export function modelLabel(name: string): string {
  const m = name.replace(/-\d+$/, "");
  return m === "codex" ? "codex" : `${m} 5.5`;
}

/** Dispatch lines look like `Task(sonnet-14)` or `spawn(codex-22)`. */
export const DISPATCH = /^(?:Task|spawn)\((.+)\)$/;

/** Workers spawned per cycle; numbers climb across cycles. */
const PER_CYCLE = 9;

/** Upper bound on a cycle. A cycle actually ends just after its last event
    (see `cycleEnd`), so the window is never idle for long. */
export const CYCLE_MS = 40_000;

/** When the driver wraps to the next cycle: a beat after the last event. */
export function cycleEnd(ev: Ev[]): number {
  return (ev.length ? ev[ev.length - 1].t : 0) + 500;
}

/** The driver starts here, after one complete cycle has already run, so the
    panes carry history. See `stateAt`. */
export const BOOT_CYCLE = 1;

/** Where the loop (and the static frame) boots: both waves dispatched, two
    claims already refused, the follow-up proposal seconds away. */
export const BOOT_T = 18_200;

function mulberry32(seed: number) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const TICK = 50;

interface SimWorker {
  name: string;
  tone: Tone;
  /** next scheduled step time */
  at: number;
  phase: "connect" | "next" | "claim" | "work" | "done" | "gone";
  /** index of the ticket this worker intends to claim / is working */
  target: number;
  /** progress lines still to emit: [time, variant] */
  progress: Array<[number, 0 | 1]>;
  finishAt: number;
}

export function buildScript(cycle: number, seedOverride?: number): Ev[] {
  const epic = EPICS[cycle % EPICS.length];
  const fleet = FLEETS[cycle % FLEETS.length];
  const T = epic.tickets;
  const rnd = mulberry32((seedOverride ?? epic.seed) * 7919 + 17);
  const ev: Ev[] = [];
  const firstWorker = cycle * PER_CYCLE + 1;

  /* ---- emit helpers -------------------------------------------------- */
  /* A call (or the human's approval line) and its ⎿ result form one block;
     `blocks` records the pairs so a post-pass can keep every other
     orchestrator line out from between them (worker completions arrive on
     their own clock and would otherwise land inside an open call). */
  const blocks: Array<[Ev, Ev]> = [];
  let opener: Ev | null = null;
  const o = (t: number, line: OrchLine): Ev => {
    const e: Ev = { t, op: "o", line };
    ev.push(e);
    if (line.kind === "human") opener = e;
    if (line.kind === "result") {
      if (opener) blocks.push([opener, e]);
      opener = null;
    }
    return e;
  };
  const ocall = (t: number, tool: string, arg = "", tone: Tone | null = null) => {
    const e = o(t, { kind: "call", tool, arg, tone, race: false });
    if (!DISPATCH.test(tool)) opener = e; // dispatch lines have no result
  };
  const ores = (t: number, text: string, tone: ResultTone = "ok") => o(t, { kind: "result", text, tone, race: false });
  const w = (t: number, name: string, line: WorkerLine) => ev.push({ t, op: "w", name, line });
  const call = (t: number, name: string, tool: string, arg = "", race = false) =>
    w(t, name, { kind: "call", tool, arg, tone: null, race });
  const res = (t: number, name: string, text: string, tone: ResultTone = "ok", race = false) =>
    w(t, name, { kind: "result", text, tone, race });

  /* ---- ticket truth, advanced tick by tick --------------------------- */
  const state: TicketState[] = T.map(() => "proposed");
  const holder: (string | null)[] = T.map(() => null);
  const readyCount = () => state.filter((s) => s === "approved").length;
  const doneCount = () => state.filter((s) => s === "done").length;
  const execCount = () => state.filter((s) => s === "executing").length;
  const firstReady = () => state.findIndex((s) => s === "approved");

  /* ---- orchestrator prologue ----------------------------------------- */
  const INIT = T.slice(0, epic.initial);
  const FOLLOW = T.slice(epic.initial);
  ev.push({ t: 0, op: "epic", name: epic.name, agent: fleet.agent });
  o(0, { kind: "user", text: epic.prompt });
  ocall(400, "canvas_connect", "role: planner");
  ores(700, "connected · planner");
  ocall(1_000, "epic_propose", `"${epic.name}" · ${INIT.length} tasks`);
  INIT.forEach((tk, i) => ev.push({ t: 1_100 + i * 40, op: "add", id: tk.id }));
  ores(1_500, `${INIT[0].id}..${INIT[INIT.length - 1].id.slice(4)} proposed · waiting on you`);
  o(1_900, { kind: "say", text: `Proposed ${INIT.length} tickets. Parked until you approve them on the board.` });
  ocall(2_400, "queue_wait");
  ores(2_700, "waiting…", "dim");
  const APPROVE = 4_200;
  o(APPROVE, { kind: "human", text: "approved on the board" });
  INIT.forEach((tk, i) => ev.push({ t: APPROVE + 50 + i * 40, op: "move", id: tk.id, state: "approved", holder: null }));
  ores(4_700, `ready · ${INIT.length} tasks`, "win");
  ocall(5_050, "queue_next");
  ores(5_400, `${INIT.length} ready · handoff blocks`);

  /* ---- simulation ---------------------------------------------------- */
  const workers: SimWorker[] = [];
  const handed = new Set<number>();
  const handedAt = new Map<number, number>();
  let spawned = 0;
  let refusals = 0;
  let waveIdx = 0;
  let nextStatus = 10_000;
  let lastStatusAt = -Infinity;
  let followAt = -1; // when follow-ups were proposed; -1 = not yet
  let followWaveAt = Infinity;
  let drained = false;

  /* the orchestrator hands each new worker the next ticket nobody was handed */
  const unhanded = () => state.filter((st, i) => st === "approved" && !handed.has(i)).length;
  const spawn = (t: number) => {
    const n = firstWorker + spawned;
    const [model, tone] = fleet.models[(n - 1) % fleet.models.length];
    const name = `${model}-${n}`;
    spawned++;
    let h = state.findIndex((st, i) => st === "approved" && !handed.has(i));
    if (h < 0) h = firstReady();
    if (h >= 0) {
      handed.add(h);
      handedAt.set(h, t);
    }
    ocall(t, `${fleet.verb}(${name})`, h >= 0 ? T[h].id : "claim from the queue", tone);
    ev.push({ t: t + 100, op: "spawn", name, tone });
    call(t + 1_000, name, "canvas_connect", "role: executor");
    res(t + 1_350, name, "parent orchestrator");
    workers.push({ name, tone, at: t + 1_750 + Math.floor(rnd() * 6) * 50, phase: h >= 0 ? "claim" : "next", target: h, progress: [], finishAt: 0 });
  };

  for (let t = APPROVE; t < CYCLE_MS; t += TICK) {
    /* the approval lands over the first ~500 ms; mirror it in the sim truth */
    INIT.forEach((_, i) => {
      if (state[i] === "proposed" && t >= APPROVE + 50 + i * 40) state[i] = "approved";
    });

    /* orchestrator: dispatch waves, follow-ups, periodic board_status */
    const wave = epic.waves[waveIdx];
    if (wave && t >= wave[0]) {
      if (waveIdx > 0) {
        const ready = readyCount();
        o(t - 700, { kind: "say", text: `${ready} still ready with ${workers.length} on it: sending ${Math.min(wave[1], unhanded())} more.` });
      }
      const n = Math.min(wave[1], unhanded());
      for (let k = 0; k < n; k++) spawn(t + k * 650);
      waveIdx++;
      if (waveIdx === 1) o(t + wave[1] * 650 + 600, { kind: "say", text: "Subagents are on the queue. Claims are atomic; I claim nothing." });
      nextStatus = Math.max(nextStatus, t + 3_500);
    } else if (followAt < 0 && waveIdx >= epic.waves.length && readyCount() === 0 && t >= 12_500 && t >= lastStatusAt + 1_600) {
      /* backlog empty but results point at more work: add it under the same
         epic. On the default `epic` policy those land already approved. */
      followAt = t;
      o(t, { kind: "say", text: `Queue is empty while ${execCount()} are still executing. Results point at ${FOLLOW.length} follow-ups; adding them to the epic.` });
      ocall(t + 900, "task_propose", `×${FOLLOW.length} · epic "${epic.name}"`);
      FOLLOW.forEach((tk, k) => {
        ev.push({ t: t + 950 + k * 40, op: "add", id: tk.id });
        ev.push({ t: t + 1_300 + k * 40, op: "move", id: tk.id, state: "approved", holder: null });
      });
      ores(t + 1_300, `${FOLLOW[0].id}..${FOLLOW[FOLLOW.length - 1].id.slice(4)} approved · epic policy`, "win");
      followWaveAt = t + 2_600;
      nextStatus = Math.max(nextStatus, t + 3_000);
    } else if (t >= followWaveAt) {
      followWaveAt = Infinity;
      const n = Math.min(epic.followWave, unhanded());
      for (let k = 0; k < n; k++) spawn(t + k * 650);
      nextStatus = Math.max(nextStatus, t + 3_500);
    } else if (t >= nextStatus && !drained) {
      ocall(t, "board_status");
      ores(t + 400, `${doneCount()} done · ${execCount()} executing · ${readyCount()} ready`);
      lastStatusAt = t;
      nextStatus = t + 6_500;
    }
    FOLLOW.forEach((_, k) => {
      const i = epic.initial + k;
      if (followAt >= 0 && state[i] === "proposed" && t >= followAt + 1_300 + k * 40) state[i] = "approved";
    });

    /* workers */
    for (const x of workers) {
      if (x.phase === "gone" || t < x.at) continue;
      switch (x.phase) {
        case "next": {
          call(t, x.name, "queue_next");
          const ready = readyCount();
          res(t + 350, x.name, `${ready} ready`, ready === 0 ? "dim" : "ok");
          if (ready === 0) {
            /* nothing left for this one: leave */
            ev.push({ t: t + 650, op: "idle", name: x.name });
            ev.push({ t: t + 1_250, op: "remove", name: x.name });
            x.phase = "gone";
          } else {
            /* snapshot the queue head now; claim a beat later — that gap is
               where another session can beat us to it */
            /* take the queue head, skipping tickets handed to a worker that
               is still connecting (the handoff names them, they claim next) */
            let pick = state.findIndex((st, i) => st === "approved" && !(handedAt.has(i) && t - (handedAt.get(i) as number) < 3_000));
            if (pick < 0) pick = firstReady();
            x.target = pick;
            x.phase = "claim";
            x.at = t + 350 + 150 + Math.floor(rnd() * 5) * 50;
          }
          break;
        }
        case "claim": {
          const i = x.target;
          const id = T[i].id;
          if (state[i] === "approved") {
            call(t, x.name, "task_claim", id);
            res(t + 400, x.name, "claimed", "win");
            state[i] = "executing";
            holder[i] = x.name;
            ev.push({ t: t + 400, op: "move", id, state: "executing", holder: x.name });
            ev.push({ t: t + 400, op: "current", name: x.name, ticket: id });
            const work = 2_800 + Math.floor(rnd() * 80) * 50;
            x.progress = [[t + 1_300 + Math.floor(rnd() * 10) * 50, 0]];
            if (work > 4_400) x.progress.push([t + Math.floor(work * 0.62), 1]);
            x.finishAt = t + 400 + work;
            x.phase = "work";
            x.at = t + 400;
          } else {
            call(t, x.name, "task_claim", id, true);
            const by = holder[i];
            res(t + 400, x.name, by && state[i] === "executing" ? `claimed: false · held by ${by}` : "claimed: false · already done", "lose", true);
            ev.push({ t: t + 400, op: "refused" });
            refusals++;
            x.phase = "next";
            x.at = t + 400 + 450 + Math.floor(rnd() * 6) * 50;
          }
          break;
        }
        case "work": {
          while (x.progress.length && x.progress[0][0] <= t) {
            const [, k] = x.progress.shift() as [number, 0 | 1];
            call(t, x.name, "task_progress", `"${T[x.target].progress[k]}"`);
          }
          if (t >= x.finishAt) {
            const i = x.target;
            call(t, x.name, "task_complete", T[i].id);
            res(t + 450, x.name, T[i].hash, "win");
            state[i] = "done";
            ev.push({ t: t + 450, op: "move", id: T[i].id, state: "done", holder: x.name });
            ev.push({ t: t + 450, op: "current", name: x.name, ticket: null });
            x.phase = "next";
            x.at = t + 450 + 400 + Math.floor(rnd() * 8) * 50;
          }
          break;
        }
      }
    }

    /* everything done and every worker gone: close the epic */
    if (!drained && doneCount() === T.length && workers.every((x) => x.phase === "gone")) {
      drained = true;
      const c = t + 700;
      ocall(c, "board_status");
      ores(c + 400, `${T.length} done · 0 executing`, "win");
      o(c + 900, {
        kind: "say",
        text: `Epic done: ${T.length} tickets, ${T.length} commits, ${refusals} claims refused and retried. Waiting for the next approval.`,
      });
      ocall(c + 1_400, "queue_wait");
      ores(c + 1_700, "waiting…", "dim");
      ev.push({ t: Math.min(CYCLE_MS - 600, c + 2_000), op: "clear" });
      break;
    }
  }

  /* keep each orchestrator block atomic: anything else that would print
     between an opener and its result moves to just after the result */
  for (let pass = 0; pass < 8; pass++) {
    let moved = false;
    for (const [c, r] of blocks) {
      for (const e of ev) {
        if (e.op !== "o" || e === c || e === r) continue;
        if (e.t >= c.t && e.t <= r.t) {
          e.t = r.t + 10;
          moved = true;
        }
      }
    }
    if (!moved) break;
  }

  ev.sort((a, b) => a.t - b.t);
  return ev;
}

const MAX_ORCH = 48;
const MAX_WORKER = 16;

export const EMPTY: BoardState = { epic: "", agent: "", tickets: [], orch: [], workers: [], refused: 0, seq: 0 };

export function reduce(s: BoardState, e: Ev): BoardState {
  switch (e.op) {
    case "epic":
      return { ...s, epic: e.name, agent: e.agent };
    case "add":
      return { ...s, tickets: [...s.tickets, { id: e.id, state: "proposed", holder: null }] };
    case "move":
      return { ...s, tickets: s.tickets.map((t) => (t.id === e.id ? { ...t, state: e.state, holder: e.holder } : t)) };
    case "clear":
      return { ...s, tickets: [], refused: 0 };
    case "refused":
      return { ...s, refused: s.refused + 1 };
    case "o": {
      const id = s.seq + 1;
      return { ...s, seq: id, orch: [...s.orch, { id, ...e.line } as Line].slice(-MAX_ORCH) };
    }
    case "spawn":
      return {
        ...s,
        workers: [...s.workers, { name: e.name, tone: e.tone, lines: [], current: null, active: true }],
      };
    case "w": {
      const id = s.seq + 1;
      const line = { id, ...e.line } as Line;
      return {
        ...s,
        seq: id,
        workers: s.workers.map((x) => (x.name === e.name ? { ...x, lines: [...x.lines, line].slice(-MAX_WORKER) } : x)),
      };
    }
    case "current":
      return { ...s, workers: s.workers.map((x) => (x.name === e.name ? { ...x, current: e.ticket } : x)) };
    case "idle":
      return { ...s, workers: s.workers.map((x) => (x.name === e.name ? { ...x, active: false } : x)) };
    case "remove":
      return { ...s, workers: s.workers.filter((x) => x.name !== e.name) };
  }
}

/** State at time `t` of cycle BOOT_CYCLE, after the cycles before it have
    fully run, so the orchestrator transcript carries history on first paint. */
export function stateAt(t: number): BoardState {
  let s = EMPTY;
  for (let c = 0; c < BOOT_CYCLE; c++) for (const e of buildScript(c)) s = reduce(s, e);
  for (const e of buildScript(BOOT_CYCLE)) {
    if (e.t > t) break;
    s = reduce(s, e);
  }
  return s;
}

/** The frame everything boots from (SSR, reduced motion, and the live loop). */
export const BOOT_STATE: BoardState = stateAt(BOOT_T);
